    public void showPreview(MainFrame owner, CoverPage page, CoverTemplate template) {
        this.owner = owner;
        this.page = page;
        this.template = template;
        previewPanel.setContent(page, template);
        lblPreviewInfo.setText(template.getName() + "  |  A4, 210 x 297 mm");
        setTitle("Preview - " + template.getName());
        Dimension screen = Toolkit.getDefaultToolkit().getScreenSize();
        setSize(660, Math.min(840, screen.height - 80));
        setLocationRelativeTo(owner);
        if (scrollPreview != null) {
            javax.swing.SwingUtilities.invokeLater(() -> {
                scrollPreview.getVerticalScrollBar().setValue(0);
                scrollPreview.getHorizontalScrollBar().setValue(0);
            });
        }
        setVisible(true);
    }

